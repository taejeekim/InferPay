import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { factKey, sealDataset, type Dataset, type Entry, type Fact, type Hash } from "../commitment/index.ts";

type Row = { readonly salt: Hash } & { readonly [field: string]: unknown };

function rows(path: string): readonly Row[] {
  return JSON.parse(readFileSync(fileURLToPath(new URL(path, import.meta.url)), "utf8")) as readonly Row[];
}

function seal<E extends Entry>(path: string, kind: E["kind"]): Dataset<E> {
  return sealDataset(rows(path).map(({ salt, ...fields }) => ({ entry: { kind, ...fields } as unknown as E, salt })));
}

// The three sample datasets, sealed the way each shop seals its own. Read from the data files, not through the
// shops, because buyer-side code may not import a shop.
export function sampleDatasets() {
  return {
    insurance: seal<Fact>("../providers/insurance/data/coverage.json", "fact"),
    disclosure: seal("../providers/disclosure/data/samsung-q3-2025.json", "figure"),
    legal: seal("../providers/legal/data/playbook.json", "rule"),
  };
}

const ABSENT_TOPIC = "dental-implants";

// One check the insurance shop proves with an entry, and one it proves it holds nothing for.
export function siteEvidence() {
  const insurance = sampleDatasets().insurance;
  const mri = insurance.entries.find((entry) => entry.topic === "outpatient-mri");
  if (!mri) throw new Error("the insurance sample has no outpatient-mri entry");
  const vacancy = insurance.proveAbsent(factKey({ topic: ABSENT_TOPIC }));
  if (!vacancy) throw new Error(`another entry sits in the slot of ${ABSENT_TOPIC}`);
  return {
    shop: "insurance",
    commitment: insurance.commitment,
    present: {
      kind: "fact",
      claim: { label: "outpatient MRI", topic: "outpatient-mri", claimed: "covered" },
      verdict: "match",
      evidence: { ...insurance.prove(mri), entry: mri },
    },
    absent: {
      kind: "fact",
      claim: { label: "dental implants", topic: ABSENT_TOPIC, claimed: "covered" },
      verdict: "unverifiable",
      evidence: vacancy,
    },
  } as const;
}

export const EVIDENCE_MODULE = new URL("../../docs/js/evidence.js", import.meta.url);

export function evidenceModule(): string {
  return [
    "// Generated by `node src/site/evidence.ts` from src/providers/insurance/data/coverage.json. Do not edit.",
    `export default ${JSON.stringify(siteEvidence(), null, 2)};`,
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(EVIDENCE_MODULE, evidenceModule());
  console.log(`wrote ${fileURLToPath(EVIDENCE_MODULE)}`);
}
